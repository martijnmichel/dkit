import fs from "node:fs";
import path from "node:path";
import type { DkitProjectConfig } from "@dkit/shared";
import { resolveAliasPath } from "./paths.js";

/** logical collection name → type binding for schema fields */
const COLLECTION_TYPES: Record<string, { moduleId: string; typeName: string }> =
  {
    posts: { moduleId: "blog", typeName: "BlogPost" },
    authors: { moduleId: "blog", typeName: "BlogAuthor" },
    categories: { moduleId: "blog", typeName: "BlogCategory" },
    posts_categories: { moduleId: "blog", typeName: "PostsCategoriesRow" },
    pages: { moduleId: "pages", typeName: "SitePage" },
    builder_pages: { moduleId: "page-builder", typeName: "BuilderPage" },
    block_hero: { moduleId: "page-builder", typeName: "BlockHero" },
    block_richtext: { moduleId: "page-builder", typeName: "BlockRichtext" },
    block_cta: { moduleId: "page-builder", typeName: "BlockCta" },
    builder_pages_blocks: {
      moduleId: "page-builder",
      typeName: "BuilderPagesBlocksRow",
    },
    form_submissions: { moduleId: "contact-form", typeName: "FormSubmission" },
  };

/**
 * Write lib/dkit/client.ts + schema.ts.
 * Schema keys use physical collection names so `readItems(collections.posts)` type-checks.
 */
export function writeDkitClient(
  projectRoot: string,
  config: DkitProjectConfig,
  collectionMap: Record<string, string> = config.collections ?? {},
): { client: string; schema: string } {
  const libDir = resolveAliasPath(config.aliases.lib, projectRoot);
  fs.mkdirSync(libDir, { recursive: true });

  const installed = new Set(Object.keys(config.modules ?? {}));

  const importsByModule = new Map<string, Set<string>>();
  const schemaFields: string[] = [];

  for (const [logical, physical] of Object.entries(collectionMap)) {
    const binding = COLLECTION_TYPES[logical];
    if (!binding) continue;
    if (!installed.has(binding.moduleId)) continue;

    let set = importsByModule.get(binding.moduleId);
    if (!set) {
      set = new Set();
      importsByModule.set(binding.moduleId, set);
    }
    set.add(binding.typeName);
    // Regular collections must be arrays — non-arrays are treated as singletons by @directus/sdk
    schemaFields.push(
      `  ${JSON.stringify(physical)}: ${binding.typeName}[];`,
    );
  }

  const importLines = [...importsByModule.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([moduleId, types]) => {
      const names = [...types].sort().join(", ");
      return `import type { ${names} } from "./${moduleId}.types";`;
    });

  const schemaFile = path.join(libDir, "schema.ts");
  const schemaContents = `/** Generated by dkit — Directus SDK schema for installed modules.
 * Collection values are arrays (regular collections). Singletons would be bare objects.
 */
${importLines.length ? `${importLines.join("\n")}\n` : ""}
export type DkitSchema = {
${schemaFields.length ? `${schemaFields.join("\n")}\n` : ""}
};
`;
  fs.writeFileSync(schemaFile, schemaContents, "utf8");

  const clientFile = path.join(libDir, "client.ts");
  const clientContents = `/** Generated by dkit — shared typed Directus client + asset helpers.
 * Modules must import getDirectus / directusFileId / directusAssetUrl from here —
 * never redefine them in lib/dkit/<module>.ts.
 */
import {
  createDirectus,
  createItem,
  readItem,
  readItems,
  rest,
} from "@directus/sdk";
import type { DkitSchema } from "./schema";

export type { DkitSchema } from "./schema";

export type DirectusFileRef = { id: string };

/**
 * Server-side Directus client (public role / no admin token).
 * Returns null when DIRECTUS_URL is unset so pages can fail soft.
 */
export function getDirectus() {
  const url = process.env.DIRECTUS_URL;
  if (!url) return null;
  return createDirectus<DkitSchema>(url).with(rest());
}

/** Normalize a string id or expanded file object to a file id. */
export function directusFileId(
  value: string | DirectusFileRef | null | undefined,
): string | null {
  if (!value) return null;
  if (typeof value === "string") return value;
  return value.id ?? null;
}

/** Public asset URL for a Directus file id. */
export function directusAssetUrl(
  fileId: string,
  baseUrl = process.env.DIRECTUS_URL,
): string | null {
  const base = baseUrl?.replace(/\\/$/, "");
  if (!base || !fileId) return null;
  return \`\${base}/assets/\${fileId}\`;
}

export { createItem, readItem, readItems };
`;
  fs.writeFileSync(clientFile, clientContents, "utf8");

  return { client: clientFile, schema: schemaFile };
}

/** @deprecated use writeDkitClient */
export function writeClientHelper(
  projectRoot: string,
  config: DkitProjectConfig,
): string {
  return writeDkitClient(projectRoot, config).client;
}
