import fs from "node:fs";
import path from "node:path";
import type { DkitProjectConfig } from "@dkit/shared";
import { resolveAliasPath } from "./paths.js";

export function writeDkitRuntimeConfig(
  projectRoot: string,
  config: DkitProjectConfig,
  collectionMap: Record<string, string>,
): string {
  const libDir = resolveAliasPath(config.aliases.lib, projectRoot);
  fs.mkdirSync(libDir, { recursive: true });
  const file = path.join(libDir, "config.ts");

  const modulesEntries = Object.entries(config.modules ?? {})
    .map(([id, mod]) => {
      const base = mod.basePath ? JSON.stringify(mod.basePath) : "undefined";
      const blocks = mod.blocks
        ? JSON.stringify(mod.blocks)
        : "undefined";
      const slots = mod.slots ? JSON.stringify(mod.slots) : "undefined";
      return `  ${JSON.stringify(id)}: { basePath: ${base}, blocks: ${blocks}, slots: ${slots} },`;
    })
    .join("\n");

  const collectionsEntries = Object.entries(collectionMap)
    .map(([logical, physical]) => `  ${JSON.stringify(logical)}: ${JSON.stringify(physical)},`)
    .join("\n");

  const contents = `/** Generated by dkit — collection names + route bases. Safe to edit. */
export const collectionPrefix = ${JSON.stringify(config.collectionPrefix ?? "dkit_")} as const;

/** Logical registry name → physical Directus collection */
export const collections = {
${collectionsEntries}
} as const;

export type DkitCollection = keyof typeof collections;

export const modules = {
${modulesEntries}
} as const;

export function collection(name: DkitCollection): string {
  return collections[name];
}

export function moduleBasePath(moduleId: string, fallback = "/"): string {
  const mod = (modules as Record<string, { basePath?: string }>)[moduleId];
  return mod?.basePath ?? fallback;
}

/** Join module base + slug: "/" + "about" → "/about"; "/pages" + "about" → "/pages/about". */
export function joinModulePath(basePath: string, ...parts: string[]): string {
  const base = !basePath || basePath === "/" ? "" : basePath.replace(/\\/$/, "");
  const rest = parts
    .map((p) => p.replace(/^\\/+|\\/+$/g, ""))
    .filter(Boolean)
    .join("/");
  const joined = (base + "/" + rest).replace(/\\/{2,}/g, "/");
  return joined.startsWith("/") ? joined : "/" + joined;
}
`;

  fs.writeFileSync(file, contents, "utf8");
  return file;
}
